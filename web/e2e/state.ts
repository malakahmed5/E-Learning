// Values that one browser test file creates and a later file needs
// (for example the authenticator secret of the teacher registered in the first file).
// Test files do not share memory, so the values are kept in a small JSON file during the run.
// scripts/run-e2e.ps1 deletes the file before every run.

import { existsSync, readFileSync, writeFileSync } from "fs";
import { join } from "path";

// Playwright is always started from the "web" folder, so the path is built from there.
const STATE_FILE = join(process.cwd(), "e2e", ".e2e-state.json");

export interface E2eState {
  adminSecret?: string;
  teacherSecret?: string;
  // Codes generated by the platform owner in the subscription tests.
  freeWeekCode?: string;
  revokedCode?: string;
  paidCode?: string;
  // Last authenticator time step used per secret (a code cannot be used twice).
  lastUsedStep?: Record<string, number>;
}

export function readState(): E2eState {
  if (!existsSync(STATE_FILE)) {
    return {};
  }
  return JSON.parse(readFileSync(STATE_FILE, "utf8")) as E2eState;
}

export function saveState(changes: Partial<E2eState>): void {
  const next = { ...readState(), ...changes };
  writeFileSync(STATE_FILE, JSON.stringify(next, null, 2));
}
